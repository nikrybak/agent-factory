// cli/test/secret-overlay.test.js
// GEN-2: secret-split TDD — verify local overlay writes secrets and main config stays clean.
'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { loadLocalAgents, buildLocalToml, writeSecretOverlay } = require('../lib/secret-overlay');
const { syncTargets } = require('../lib/sync');

// ---------------------------------------------------------------------------
// Unit: loadLocalAgents
// ---------------------------------------------------------------------------

test('loadLocalAgents returns null when agents.local.json is absent', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-'));
  assert.strictEqual(loadLocalAgents(d), null);
});

test('loadLocalAgents parses agents.local.json and returns mcpServers', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-'));
  fs.writeFileSync(path.join(d, 'agents.local.json'), JSON.stringify({
    mcpServers: { github: { command: 'npx', env: { GITHUB_TOKEN: 'secret-abc' } } }
  }));
  const result = loadLocalAgents(d);
  assert.ok(result !== null);
  assert.strictEqual(result.mcpServers.github.env.GITHUB_TOKEN, 'secret-abc');
});

test('loadLocalAgents returns null for malformed JSON (logs to stderr, no throw)', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-'));
  fs.writeFileSync(path.join(d, 'agents.local.json'), '{ BROKEN JSON');
  assert.strictEqual(loadLocalAgents(d), null);
});

// ---------------------------------------------------------------------------
// Unit: buildLocalToml
// ---------------------------------------------------------------------------

test('buildLocalToml emits generated header and mcp_servers table', () => {
  const servers = { github: { command: 'npx', env: { GITHUB_TOKEN: 'tok' } } };
  const toml = buildLocalToml(servers);
  assert.match(toml, /GENERATED by infra/);
  assert.match(toml, /LOCAL — never commit/);
  assert.match(toml, /\[mcp_servers\.github\]/);
  assert.match(toml, /GITHUB_TOKEN/);
});

// ---------------------------------------------------------------------------
// Integration: writeSecretOverlay
// ---------------------------------------------------------------------------

test('writeSecretOverlay does nothing when agents.local.json is absent', () => {
  const from = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-from-'));
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-out-'));
  const wrote = writeSecretOverlay(from, out);
  assert.strictEqual(wrote, false);
  assert.ok(!fs.existsSync(path.join(out, '.codex', 'config.local.toml')));
});

test('writeSecretOverlay writes config.local.toml with secret server', () => {
  const from = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-from-'));
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-out-'));
  fs.writeFileSync(path.join(from, 'agents.local.json'), JSON.stringify({
    mcpServers: {
      github: {
        command: 'npx',
        args: ['-y', '@modelcontextprotocol/server-github'],
        env: { GITHUB_TOKEN: 'ghp_SUPERSECRET' }
      }
    }
  }));
  const wrote = writeSecretOverlay(from, out);
  assert.strictEqual(wrote, true);
  const dest = path.join(out, '.codex', 'config.local.toml');
  assert.ok(fs.existsSync(dest), 'config.local.toml must be created');
  const content = fs.readFileSync(dest, 'utf8');
  assert.match(content, /\[mcp_servers\.github\]/);
  assert.match(content, /GITHUB_TOKEN/);
  assert.match(content, /ghp_SUPERSECRET/);
});

// ---------------------------------------------------------------------------
// Integration: main config.toml MUST NOT contain the secret
// ---------------------------------------------------------------------------

test('main config.toml does NOT contain secret from agents.local.json', () => {
  const from = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-from-'));
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'overlay-out-'));

  // Build a canon that does NOT have the github token
  const config = {
    version: '1.0',
    canon: { agents: 'AGENTS.md', skills: 'skills' },
    targets: ['codex'],
    mcpServers: {
      github: {
        command: 'npx',
        args: ['-y', '@modelcontextprotocol/server-github']
        // no env here — public config
      }
    }
  };
  fs.writeFileSync(path.join(from, 'AGENTS.md'), '# Contract');
  fs.writeFileSync(path.join(from, 'agents.json'), JSON.stringify(config));

  // agents.local.json adds the secret env override
  fs.writeFileSync(path.join(from, 'agents.local.json'), JSON.stringify({
    mcpServers: {
      github: {
        command: 'npx',
        args: ['-y', '@modelcontextprotocol/server-github'],
        env: { GITHUB_TOKEN: 'ghp_SUPERSECRET' }
      }
    }
  }));

  const canon = { agentsMd: '# Contract', config };
  syncTargets(canon, [], out);
  writeSecretOverlay(from, out);

  const mainToml = fs.readFileSync(path.join(out, '.codex', 'config.toml'), 'utf8');
  const localToml = fs.readFileSync(path.join(out, '.codex', 'config.local.toml'), 'utf8');

  // Main config must NOT contain the secret
  assert.ok(!mainToml.includes('ghp_SUPERSECRET'),
    'main config.toml must NOT contain the secret token');

  // Local config MUST contain it
  assert.ok(localToml.includes('ghp_SUPERSECRET'),
    'config.local.toml must contain the secret token');
});
