// cli/test/generators-wrappers.test.js
const { test } = require('node:test');
const assert = require('node:assert');
const { genClaude } = require('../lib/generators/claude');
const { genGemini } = require('../lib/generators/gemini');

const canon = { agentsMd: '# Contract', config: { targets: ['claude','gemini'] }, root: '/x' };

test('genClaude emits DO NOT EDIT header and @AGENTS.md import', () => {
  const out = genClaude(canon);
  assert.match(out, /GENERATED by infra — DO NOT EDIT\. Source: AGENTS\.md/);
  assert.match(out, /@AGENTS\.md/);
});

test('genGemini imports AGENTS.md via @ path', () => {
  const out = genGemini(canon);
  assert.match(out, /GENERATED by infra — DO NOT EDIT/);
  assert.match(out, /@\.\/AGENTS\.md/);
});
