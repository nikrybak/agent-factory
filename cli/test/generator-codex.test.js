// cli/test/generator-codex.test.js
const { test } = require('node:test');
const assert = require('node:assert');
const { genCodex } = require('../lib/generators/codex');

const canon = { agentsMd: '', config: { mcpServers: {
  filesystem: { command: 'npx', args: ['-y', '@modelcontextprotocol/server-filesystem', '.'] },
  sentry: { url: 'https://mcp.sentry.dev/mcp' }
} } };

test('genCodex emits header, instructions pointer and MCP tables', () => {
  const out = genCodex(canon);
  assert.match(out, /# GENERATED by infra/);
  assert.match(out, /persistent_instructions = "Follow project AGENTS\.md\."/);
  assert.match(out, /\[mcp_servers\.filesystem\]/);
  assert.match(out, /command = "npx"/);
  assert.match(out, /\[mcp_servers\.sentry\]/);
  assert.match(out, /url = "https:\/\/mcp\.sentry\.dev\/mcp"/);
});
